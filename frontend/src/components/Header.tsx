import type { AppConfig } from '../api/types'

const providerName = { openai: 'OpenAI', foundry: 'Microsoft Foundry' } as const

interface Props {
  config: AppConfig | null
  onHome: () => void
  onHistory: () => void
}

export function Header({ config, onHome, onHistory }: Props) {
  return (
    <header className="mx-auto flex w-full max-w-3xl flex-wrap items-center justify-between gap-3 px-4 py-5 sm:px-6">
      <button onClick={onHome} className="flex items-center gap-2.5 rounded-md text-left">
        <img src="/favicon.svg" alt="" className="size-7" />
        <span className="font-serif text-xl font-medium tracking-tight">Mini AI Interviewer</span>
      </button>

      <nav className="flex items-center gap-1 text-[14px]">
        <button
          onClick={onHistory}
          className="rounded-md px-3 py-1.5 text-muted transition-colors hover:bg-rule/50 hover:text-ink"
        >
          Past interviews
        </button>
        {config && <ProviderBadge config={config} />}
      </nav>
    </header>
  )
}

function ProviderBadge({ config }: { config: AppConfig }) {
  if (config.demo) {
    return (
      <span
        className="rounded-md bg-marker/70 px-2.5 py-1 font-medium text-ink"
        title="No API key configured. Responses are canned."
      >
        Demo mode
      </span>
    )
  }
  return (
    <span
      className="flex items-center gap-2 rounded-md border border-rule bg-surface px-2.5 py-1 text-muted"
      title={`Questions and summaries are generated by ${config.model}`}
    >
      <span className="size-1.5 rounded-full bg-action" aria-hidden />
      {providerName[config.provider]} <span className="text-ink">{config.model}</span>
    </span>
  )
}

export function DemoBanner() {
  return (
    <div className="mx-auto w-full max-w-3xl px-4 sm:px-6">
      <p className="rounded-lg border border-rule bg-surface px-4 py-3 text-[14px] leading-relaxed text-muted">
        <span className="font-medium text-ink">You're in demo mode.</span> Questions and summaries
        are canned examples. Add an API key to <code className="text-ink">.env</code> and restart
        the backend to use a real model.
      </p>
    </div>
  )
}
