import type { ClassicAnalysis, Interview, Summary } from '../api/types'
import { Button, Section, SentimentDot } from '../components/ui'
import { formatDate } from '../lib/format'

interface Props {
  interview: Interview
  onNew: () => void
  onHistory: () => void
}

export function SummaryScreen({ interview, onNew, onHistory }: Props) {
  const { summary, analysis } = interview
  if (!summary) return null

  return (
    <article className="space-y-12">
      <header className="space-y-5">
        <p className="text-[15px] text-muted">
          Your interview on <span className="text-ink">{interview.topic}</span>,{' '}
          {formatDate(interview.completed_at)}
        </p>
        <h1 className="font-serif text-[1.7rem] leading-snug tracking-tight sm:text-[2rem]">
          {summary.overview}
        </h1>
        <div className="flex flex-wrap items-center gap-x-5 gap-y-2 text-[15px]">
          <SentimentDot label={summary.sentiment.label} />
          {summary.emotions.map((e) => (
            <span key={e.name} className="text-muted">
              <span className="text-ink capitalize">{e.name}</span> ({e.intensity})
            </span>
          ))}
        </div>
      </header>

      <Section title="What we learned">
        <ol className="space-y-7">
          {summary.findings.map((f, i) => (
            <li key={i} className="grid grid-cols-[1.75rem_1fr] gap-x-2">
              <span className="font-serif text-lg text-muted">{i + 1}</span>
              <div className="space-y-2">
                <h3 className="text-[15px] font-semibold">{f.objective}</h3>
                <p className="text-[16px] leading-relaxed">{f.finding}</p>
                {f.quote && (
                  <blockquote className="font-serif text-[18px] leading-relaxed italic">
                    <span
                      className="marker marker-reveal"
                      style={{ animationDelay: `${300 + i * 180}ms` }}
                    >
                      “{f.quote.replace(/^["“]|["”]$/g, '')}”
                    </span>
                  </blockquote>
                )}
              </div>
            </li>
          ))}
        </ol>
      </Section>

      <div className="grid gap-12 sm:grid-cols-2 sm:gap-8">
        <Section title="Themes">
          <dl className="space-y-4">
            {summary.themes.map((t) => (
              <div key={t.name}>
                <dt className="font-medium">{t.name}</dt>
                <dd className="text-[15px] leading-relaxed text-muted">{t.description}</dd>
              </div>
            ))}
          </dl>
        </Section>
        <Section title="Key points">
          <ul className="list-disc space-y-2 pl-5 text-[15px] leading-relaxed marker:text-rule">
            {summary.key_points.map((p) => (
              <li key={p}>{p}</li>
            ))}
          </ul>
        </Section>
      </div>

      {analysis && <Comparison summary={summary} analysis={analysis} />}

      <Section title="Transcript">
        <details className="group">
          <summary className="cursor-pointer text-[15px] text-muted select-none hover:text-ink">
            Show all {interview.turns.length} questions and answers
          </summary>
          <ol className="mt-5 space-y-6">
            {interview.turns.map((t, i) => (
              <li key={i} className="space-y-1.5">
                <p className="font-serif text-[18px]">{t.question}</p>
                <p className="text-[15px] leading-relaxed text-muted">{t.answer}</p>
              </li>
            ))}
          </ol>
        </details>
      </Section>

      <footer className="flex flex-wrap gap-3 border-t border-rule pt-6">
        <Button onClick={onNew}>Start a new interview</Button>
        <Button variant="quiet" onClick={onHistory}>
          Past interviews
        </Button>
        <p className="ml-auto self-center text-[13px] text-muted">
          {interview.provider === 'demo'
            ? 'Generated in demo mode'
            : `Generated by ${interview.model}`}
          . Interview ID {interview.id}
        </p>
      </footer>
    </article>
  )
}

/** The AI's reading next to a classic, non-AI baseline (VADER + YAKE). */
function Comparison({ summary, analysis }: { summary: Summary; analysis: ClassicAnalysis }) {
  const shared = new Set(
    summary.keywords.map((k) => k.toLowerCase()).filter((k) => analysis.keywords.includes(k)),
  )
  return (
    <Section title="Two readings of your answers">
      <p className="-mt-2 mb-6 max-w-xl text-[15px] leading-relaxed text-muted">
        The AI reads for meaning. VADER and YAKE are classic, rule-based tools that count words.
        Where they disagree, the difference usually comes from nuance such as sarcasm or “yes, but”.
      </p>

      <div className="space-y-8">
        <div className="space-y-3">
          <h3 className="text-[15px] font-medium">Sentiment</h3>
          <SentimentScale ai={summary.sentiment.score} classic={analysis.sentiment_score} />
          <div className="grid gap-x-8 gap-y-2 text-[15px] sm:grid-cols-2">
            <p>
              <span className="font-medium">AI:</span>{' '}
              <SentimentDot label={summary.sentiment.label} />{' '}
              <span className="text-muted">({summary.sentiment.score.toFixed(2)})</span>
              <span className="mt-1 block text-[14px] leading-relaxed text-muted">
                {summary.sentiment.rationale}
              </span>
            </p>
            <p>
              <span className="font-medium">VADER:</span>{' '}
              <SentimentDot label={analysis.sentiment_label} />{' '}
              <span className="text-muted">({analysis.sentiment_score.toFixed(2)})</span>
              <span className="mt-1 block text-[14px] text-muted">
                Per answer: {analysis.answer_scores.map((s) => s.toFixed(2)).join(', ')}
              </span>
            </p>
          </div>
        </div>

        <div className="grid gap-6 sm:grid-cols-2 sm:gap-8">
          <KeywordList title="AI keywords" words={summary.keywords} shared={shared} />
          <KeywordList title="YAKE keywords" words={analysis.keywords} shared={shared} />
        </div>
        {shared.size > 0 && (
          <p className="-mt-3 text-[14px] text-muted">
            <span className="marker">Highlighted</span> keywords were found by both.
          </p>
        )}
      </div>
    </Section>
  )
}

function SentimentScale({ ai, classic }: { ai: number; classic: number }) {
  const pos = (v: number) => `${((Math.max(-1, Math.min(1, v)) + 1) / 2) * 100}%`
  return (
    <div
      className="pt-7 pb-6"
      role="img"
      aria-label={`AI score ${ai.toFixed(2)}, VADER score ${classic.toFixed(2)}, on a scale from -1 to 1`}
    >
      <div className="relative h-1.5 rounded-full bg-gradient-to-r from-negative/50 via-rule to-positive/50">
        <span className="absolute top-1/2 left-1/2 h-3 w-px -translate-y-1/2 bg-muted/50" />
        <Pin left={pos(ai)} label="AI" className="bg-ink" above />
        <Pin left={pos(classic)} label="VADER" className="bg-action" />
      </div>
      <div className="mt-1 flex justify-between text-[12px] text-muted">
        <span>Negative</span>
        <span>Positive</span>
      </div>
    </div>
  )
}

function Pin({
  left,
  label,
  className,
  above = false,
}: {
  left: string
  label: string
  className: string
  above?: boolean
}) {
  return (
    <span className="absolute top-1/2 -translate-x-1/2 -translate-y-1/2" style={{ left }}>
      <span className={`block size-3.5 rounded-full border-2 border-paper ${className}`} />
      <span
        className={`absolute left-1/2 -translate-x-1/2 text-[12px] font-medium whitespace-nowrap ${above ? 'bottom-5' : 'top-5'}`}
      >
        {label}
      </span>
    </span>
  )
}

function KeywordList({
  title,
  words,
  shared,
}: {
  title: string
  words: string[]
  shared: Set<string>
}) {
  return (
    <div className="space-y-2">
      <h3 className="text-[15px] font-medium">{title}</h3>
      <ul className="flex flex-wrap gap-x-3 gap-y-1.5 text-[15px]">
        {words.map((w) => (
          <li key={w} className={shared.has(w.toLowerCase()) ? 'marker' : 'text-muted'}>
            {w}
          </li>
        ))}
      </ul>
    </div>
  )
}
